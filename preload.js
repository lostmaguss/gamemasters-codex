const { contextBridge, ipcRenderer, webUtils, webFrame } = require("electron");
const on = (ch, fn) => { const h = (_e, v) => fn(v); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };

contextBridge.exposeInMainWorld("codex", {
  platform: process.platform,
  load: () => ipcRenderer.invoke("data:load"),
  save: text => ipcRenderer.invoke("data:save", text),
  exportData: (text, name, kind) => ipcRenderer.invoke("data:export", { text, name, kind }),
  importData: kind => ipcRenderer.invoke("data:import", kind),
  openFolder: () => ipcRenderer.invoke("data:folder"),
  backups: () => ipcRenderer.invoke("data:backups"),
  restore: name => ipcRenderer.invoke("data:restore", name),
  importMedia: paths => ipcRenderer.invoke("media:import", paths),
  removeMedia: file => ipcRenderer.invoke("media:remove", file),
  saveMedia: (dataURL, ext) => ipcRenderer.invoke("media:saveData", { dataURL, ext }),
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch { return null; } },
  version: () => ipcRenderer.invoke("app:version"),
  legal: () => ipcRenderer.invoke("app:legal"),
  zoom: f => { if (f) webFrame.setZoomFactor(f); return webFrame.getZoomFactor(); },
  discord: req => ipcRenderer.invoke("discord:send", req),
  printPDF: o => ipcRenderer.invoke("print:pdf", o),
  importNotes: dir => ipcRenderer.invoke("notes:importFolder", dir),
  bot: {
    start: token => ipcRenderer.send("bot:start", token),
    stop: () => ipcRenderer.send("bot:stop"),
    status: () => ipcRenderer.invoke("bot:status"),
    onStatus: fn => on("bot:status", fn),
    onRoll: fn => on("bot:roll", fn),
    reply: r => ipcRenderer.send("bot:result", r),
    config: c => ipcRenderer.send("bot:config", c),
    dm: m => ipcRenderer.invoke("bot:dm", m),
    fake: req => ipcRenderer.invoke("bot:fake", req),
    poll: cmd => ipcRenderer.invoke("bot:poll", cmd),
    onVote: fn => on("bot:vote", fn),
    fakeVote: v => ipcRenderer.invoke("bot:fakeVote", v),
  },
  table: {
    start: o => ipcRenderer.invoke("table:start", o),
    stop: () => ipcRenderer.invoke("table:stop"),
    info: () => ipcRenderer.invoke("table:info"),
    qr: text => ipcRenderer.invoke("table:qr", text),
    tunnel: on => ipcRenderer.invoke("table:tunnel", on),
    setIp: ip => ipcRenderer.invoke("table:ip", ip),
    firewall: () => ipcRenderer.invoke("table:firewall"),
    players: v => ipcRenderer.send("table:players", v),
    inbox: (member, list) => ipcRenderer.send("table:inbox", { member, list }),
    to: (member, t, v) => ipcRenderer.send("table:to", { member, t, v }),
    mine: (member, t, v) => ipcRenderer.send("table:mine", { member, t, v }),
    online: () => ipcRenderer.invoke("table:online"),
    onStatus: fn => on("table:status", fn),
    onAct: fn => on("table:act", fn),
    gmState: v => ipcRenderer.send("table:gmstate", v),
    gmResult: v => ipcRenderer.send("table:gmresult", v),
    gmOnline: () => ipcRenderer.invoke("table:gmOnline"),
    onGm: fn => on("table:gm", fn),
  },
  update: {
    check: () => ipcRenderer.invoke("update:check"),
    install: () => ipcRenderer.send("update:install"),
    page: () => ipcRenderer.send("update:page"),
    onState: fn => on("update:state", fn),
  },
  win: {
    min: () => ipcRenderer.send("win:min"),
    max: () => ipcRenderer.send("win:max"),
    close: () => ipcRenderer.send("win:close"),
    onState: fn => on("win:state", fn),
  },
  stage: {
    open: () => ipcRenderer.send("stage:open"),
    close: () => ipcRenderer.send("stage:close"),
    isOpen: () => ipcRenderer.invoke("stage:isOpen"),
    onTop: v => ipcRenderer.send("stage:ontop", v),
    roll: req => ipcRenderer.send("stage:roll", req),
    clear: () => ipcRenderer.send("stage:clear"),
    sound: cmd => ipcRenderer.send("stage:sound", cmd),
    show: h => ipcRenderer.send("stage:show", h),
    hide: () => ipcRenderer.send("stage:hide"),
    overlay: o => ipcRenderer.send("stage:overlay", o),
    screens: () => ipcRenderer.invoke("stage:screens"),
    toScreen: id => ipcRenderer.invoke("stage:toScreen", id),
    windowed: () => ipcRenderer.send("stage:windowed"),
    onTableMode: fn => on("stage:tableMode", fn),
    onOverlay: fn => on("stage:overlay", fn),
    onSound: fn => on("stage:sound", fn),
    onShow: fn => on("stage:show", fn),
    onHide: fn => on("stage:hide", fn),
    onState: fn => on("stage:state", fn),
    onResult: fn => on("stage:result", fn),
    // used inside the stream window
    onRoll: fn => on("stage:roll", fn),
    onClear: fn => on("stage:clear", fn),
    sendResult: res => ipcRenderer.send("stage:result", res),
  },
});
