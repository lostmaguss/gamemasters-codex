const DICTS = { tr: TR };
// the parts of the page that hold the GM's own writing, names and game text
const SKIP = ".prose, .cx-item b, .tw b, .cb-who b, [contenteditable], .lib-txt, .rr-item, .rr-body, .legal, .hand-meta b, .mcard, .tcard, code, kbd, pre, textarea, script, style, .no-tr";
const ATTRS = ["placeholder", "title", "aria-label"];
let lang = "en", obs = null;

const exact = s => DICTS[lang]?.[s];
function tr(s) {
  const k = s.trim(); if (!k || k.length > 400) return null;
  let v = exact(k);
  if (v == null) for (const [re, fn] of PATTERNS) { const m = k.match(re); if (m) { v = fn(m, x => exact(x)) || null; if (v) break; } }
  if (v == null || v === k) return null;
  return s.replace(k, v);
}
const skipped = el => !el || el.closest?.(SKIP);
// a text box's own hint is ours to translate, even though what's typed in it isn't
const attrSkipped = el => !el || (el.matches?.("textarea, [contenteditable]") ? el.parentElement?.closest(SKIP) : el.closest?.(SKIP));
function textNode(n) {
  const p = n.parentElement; if (skipped(p)) return;
  const v = tr(n.nodeValue); if (v != null && v !== n.nodeValue) n.nodeValue = v;
}
function attrs(el) {
  if (attrSkipped(el)) return;
  for (const a of ATTRS) { const s = el.getAttribute?.(a); if (!s) continue; const v = tr(s); if (v != null && v !== s) el.setAttribute(a, v); }
}
function walk(root) {
  if (root.nodeType === 3) return textNode(root);
  if (root.nodeType !== 1) return;
  attrs(root);
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = w.nextNode(); n; n = w.nextNode()) n.nodeType === 3 ? textNode(n) : attrs(n);
}
export function deskT(s) { return lang === "en" ? s : tr(String(s)) ?? s; }
export const deskLang = () => lang;
// set at startup; switching back to English reloads the window, since the page has already been rewritten
export function setDeskLang(l) {
  l = DICTS[l] ? l : "en";
  if (l === lang) return;
  lang = l; document.documentElement.lang = l;
  obs?.disconnect(); obs = null;
  if (l === "en") return;
  walk(document.body);
  obs = new MutationObserver(list => {
    for (const m of list) {
      if (m.type === "characterData") textNode(m.target);
      else if (m.type === "attributes") attrs(m.target);
      else m.addedNodes.forEach(walk);
    }
  });
  obs.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
