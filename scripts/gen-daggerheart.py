import re, json, sys, os
# Usage: python3 gen-daggerheart.py <clone of github.com/seansbox/daggerheart-srd> app/lib-daggerheart.js
D = sys.argv[1]; OUT = sys.argv[2]
def dice(t):  # **d8+2** → `1d8+2`; other bold → plain
    t = re.sub(r'\*\*(\d*)d(\d+)([+-]\d+)?\*\*', lambda m: f"`{m.group(1) or '1'}d{m.group(2)}{m.group(3) or ''}`", t)
    return re.sub(r'\*\*_?|_?\*\*|(?<!\w)_|_(?!\w)', '', t).strip()
def adv(name):
    s = open(f"{D}/adversaries/{name}.md").read()
    tier, typ = re.search(r'\*\*_Tier (\d) ([\w ]+?)\._\*\*', s).groups()
    desc = re.search(r'\*\*_Tier.*?_\*\* _(.*?)_', s).group(1)
    g = lambda k: (re.search(r'\*\*' + k + r':\*\* ([^|\n]+)', s) or [None, ""])[1].strip()
    atk = re.search(r'\*\*ATK:\*\* ([+-]\d+) \| \*\*(.+?):\*\* (\w[\w ]*) \| (\S+) (\w+)', s)
    ab = []
    if atk:
        bonus, wname, rng, dmg, kind = atk.groups()
        kind = {"phy": "physical", "mag": "magic"}.get(kind, kind)
        if "d" in dmg: ab.append([wname, "1d20" + bonus, f"{rng} range, {kind} damage.", dmg if re.match(r'^\d', dmg) else "1" + dmg])
        else: ab.append([wname, "1d20" + bonus, f"{rng} range, {dmg} {kind} damage.", ""])
    for m in re.finditer(r'\*\*_(.+?) - (Passive|Action|Reaction)_?:?_?\*\*:? ?(.*)', s):
        ab.append([f"{m.group(1)} ({m.group(2).lower()})", "", dice(m.group(3)), ""])
    motives = g("Motives & Tactics")
    threat = min(5, int(tier) + (1 if typ in ("Solo", "Leader", "Bruiser") else 0) - (1 if typ == "Minion" else 0))
    return [name, f"Tier {tier} {typ.lower()} · {desc}", max(1, threat), [g("HP"), g("Difficulty"), g("Stress"), atk.group(1) if atk else "", g("Thresholds"), tier], ab, motives]
def card(fn):
    s = open(f"{D}/abilities/{fn}").read()
    m = re.search(r'\*\*_Level (\d+)_\*\* _(\w+) (\w+)\._ \*\*_Recall Cost_\*\* _(\d+)\._', s)
    if not m or m.group(1) != "1": return None
    body = dice(s.split(m.group(0), 1)[1].strip())
    return [s.splitlines()[0].lstrip("# ").strip(), f"Level 1 · {m.group(2)} {m.group(3).lower()} · recall {m.group(4)}", body]
ADV = ["Jagged Knife Lackey", "Jagged Knife Bandit", "Giant Rat", "Dire Wolf", "Skeleton Warrior", "Shambling Zombie", "Cult Fang", "Bear", "Cave Ogre", "Minor Demon", "Vampire", "Young Ice Dragon", "Volcanic Dragon Obsidian Predator"]
creatures = [adv(a) for a in ADV]
cards = sorted([c for c in (card(f) for f in os.listdir(f"{D}/abilities")) if c], key=lambda c: (c[1].split("·")[1], c[0]))
js = """// Daggerheart: adversaries and level-1 domain cards from the Daggerheart System Reference Document 1.0.
// This includes materials from the Daggerheart System Reference Document 1.0, © Critical Role, LLC.
// under the terms of the Darrington Press Community Gaming (DPCGL) License. Generated by scripts/gen-daggerheart.py.
export default {
  daggerheart: {
    label: "Domain cards",
    creatures: """ + json.dumps(creatures, ensure_ascii=False, indent=None) + """,
    spells: """ + json.dumps(cards, ensure_ascii=False, indent=None) + """,
  },
};
"""
open(OUT, "w").write(js)
print(len(creatures), "adversaries,", len(cards), "cards")
for c in creatures: print(c[0], c[1][:30], c[3], [a[0] for a in c[4]][:3])
